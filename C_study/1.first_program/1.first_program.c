#include <stdio.h> /*include external software library: Standard Input & Output*/

int main(void){
    printf("helloworld\n");/*\n:starting a new line*/
    printf("hell\tow\torl\td\n");/*\t:move cursor to next tab stop*/
    printf("helloworld\\\n");/*\\:showing \ in a string*/
    printf("helloworld\"\n");/*\":showing " in a string"*/
    return 0;
}